import { AwsClient } from 'aws4fetch';
import { z } from 'zod';

/** Object storage behind an interface: SeaweedFS locally, Cloudflare R2 in production (ADR 0003). */
export interface ObjectStorage {
  put(key: string, body: Uint8Array, contentType: string): Promise<void>;
  /** The raw response (stream it); null if the object doesn't exist. */
  get(key: string): Promise<Response | null>;
  delete(key: string): Promise<void>;
  list(prefix: string): Promise<{ key: string; lastModified: Date }[]>;
}

const StorageConfigSchema = z.object({
  S3_ENDPOINT: z.url({ protocol: /^https?$/ }),
  S3_REGION: z.string().min(1).default('auto'),
  S3_BUCKET: z.string().regex(/^[a-z0-9][a-z0-9.-]{1,61}[a-z0-9]$/),
  S3_ACCESS_KEY_ID: z.string().min(1),
  S3_SECRET_ACCESS_KEY: z.string().min(1),
});
export type StorageConfig = z.infer<typeof StorageConfigSchema>;

export function loadStorageConfig(env: NodeJS.ProcessEnv = process.env): StorageConfig {
  const result = StorageConfigSchema.safeParse(env);
  if (!result.success)
    throw new Error(`Invalid storage configuration:\n${z.prettifyError(result.error)}`);
  return result.data;
}

/** Keys are generated by us, but never let one escape its bucket path. */
const KEY = /^[a-z0-9][a-z0-9/_.-]{0,200}$/;
function checkKey(key: string): string {
  if (!KEY.test(key) || key.includes('..')) throw new RangeError(`Invalid object key "${key}"`);
  return key;
}

const decodeXml = (s: string) =>
  s.replace(
    /&(lt|gt|amp|quot|apos);/g,
    (_, e: string) => ({ lt: '<', gt: '>', amp: '&', quot: '"', apos: "'" })[e] ?? '',
  );

/** Minimal S3 client (path-style requests, SigV4 via aws4fetch) — works with SeaweedFS, R2, MinIO, AWS. */
export class S3Storage implements ObjectStorage {
  private readonly client: AwsClient;
  private readonly base: string;

  constructor(config: StorageConfig) {
    this.client = new AwsClient({
      accessKeyId: config.S3_ACCESS_KEY_ID,
      secretAccessKey: config.S3_SECRET_ACCESS_KEY,
      region: config.S3_REGION === 'auto' ? 'us-east-1' : config.S3_REGION,
      service: 's3',
      // aws4fetch retries 5xx up to 10× by default — far too long inside an API request.
      retries: 2,
      initRetryMs: 100,
    });
    this.base = `${config.S3_ENDPOINT.replace(/\/$/, '')}/${config.S3_BUCKET}`;
  }

  private url(key: string): string {
    return `${this.base}/${checkKey(key).split('/').map(encodeURIComponent).join('/')}`;
  }

  async put(key: string, body: Uint8Array, contentType: string): Promise<void> {
    const res = await this.client.fetch(this.url(key), {
      method: 'PUT',
      body,
      headers: { 'content-type': contentType },
      signal: AbortSignal.timeout(60_000),
    });
    if (!res.ok) throw new Error(`S3 PUT ${key} failed: ${String(res.status)}`);
  }

  async get(key: string): Promise<Response | null> {
    const res = await this.client.fetch(this.url(key), { signal: AbortSignal.timeout(30_000) });
    if (res.status === 404) return null;
    if (!res.ok) throw new Error(`S3 GET ${key} failed: ${String(res.status)}`);
    return res;
  }

  async delete(key: string): Promise<void> {
    const res = await this.client.fetch(this.url(key), {
      method: 'DELETE',
      signal: AbortSignal.timeout(30_000),
    });
    if (!res.ok && res.status !== 404)
      throw new Error(`S3 DELETE ${key} failed: ${String(res.status)}`);
  }

  async list(prefix: string): Promise<{ key: string; lastModified: Date }[]> {
    const out: { key: string; lastModified: Date }[] = [];
    let token: string | undefined;
    do {
      const params = new URLSearchParams({ 'list-type': '2', prefix: checkKey(prefix) });
      if (token) params.set('continuation-token', token);
      const res = await this.client.fetch(`${this.base}?${params.toString()}`, {
        signal: AbortSignal.timeout(30_000),
      });
      if (!res.ok) throw new Error(`S3 LIST ${prefix} failed: ${String(res.status)}`);
      const xml = await res.text();
      for (const [, body = ''] of xml.matchAll(/<Contents>([\s\S]*?)<\/Contents>/g)) {
        const key = /<Key>([^<]*)<\/Key>/.exec(body)?.[1];
        const modified = /<LastModified>([^<]*)<\/LastModified>/.exec(body)?.[1];
        if (key && modified) out.push({ key: decodeXml(key), lastModified: new Date(modified) });
      }
      token = xml.includes('<IsTruncated>true</IsTruncated>')
        ? /<NextContinuationToken>([^<]*)<\/NextContinuationToken>/.exec(xml)?.[1]
        : undefined;
    } while (token);
    return out;
  }
}
